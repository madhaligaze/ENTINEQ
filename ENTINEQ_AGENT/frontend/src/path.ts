/** Сегмент пути из точек, в том числе записанных как %2e: «.», «..», «.%2e», «%2e%2e» и так далее. */
const DOT_SEGMENT = /^(\.|%2e){1,2}$/i;

/** В путях API нет пустых сегментов (двойной слеш), обратных слешей, закодированных слешей и нулевого байта. */
const FORBIDDEN = /\/\/|\\|%2f|%5c|%00/i;

/**
 * Нельзя ли пересылать такой адрес на бэкенд. Разбор URL при пересылке «схлопывает» ../ и тем самым мог бы
 * вывести запрос из /api на другие адреса бэкенда, поэтому такие пути отклоняются целиком, не доходя до него.
 * Строка запроса (после «?») не проверяется: это данные, а не путь.
 * Проверка не зависит от того, отсекает ли такие адреса сам веб-фреймворк.
 */
export function isSuspiciousPath(rawUrl: string): boolean {
  const path = rawUrl.split("?", 1)[0] ?? "";
  if (FORBIDDEN.test(path)) return true;
  return path.split("/").some((segment) => DOT_SEGMENT.test(segment));
}
